-- 1. Buat Tabel Armada Mobil (cars)
CREATE TABLE IF NOT EXISTS public.cars (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    type VARCHAR(50) NOT NULL, -- MPV, SUV, Hatchback, dll
    seats INT NOT NULL DEFAULT 5,
    transmission VARCHAR(30) NOT NULL DEFAULT 'Matic',
    price VARCHAR(20) NOT NULL, -- Contoh: '349K' atau 'Rp 349.000'
    price_number INT NOT NULL DEFAULT 0, -- Angka murni untuk kalkulasi: 349000
    rating NUMERIC(2, 1) NOT NULL DEFAULT 5.0,
    popular BOOLEAN NOT NULL DEFAULT false,
    image TEXT NOT NULL,
    engine VARCHAR(100),
    fuel VARCHAR(50) DEFAULT 'Bensin',
    luggage VARCHAR(100),
    ac VARCHAR(100),
    description TEXT,
    features JSONB DEFAULT '[]'::jsonb,
    video_url TEXT,
    is_available BOOLEAN NOT NULL DEFAULT true,
    order_index INT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Aktifkan Row Level Security (RLS) & Beri Akses Baca Publik
-- Ini agar website Anda di Netlify bisa membaca data mobil tanpa login
ALTER TABLE public.cars ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Akses publik untuk membaca mobil aktif" 
ON public.cars 
FOR SELECT 
USING (is_available = true);

-- 3. Buat Tabel Data Booking / Lead Pelanggan (Optional untuk masa depan)
CREATE TABLE IF NOT EXISTS public.bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_code VARCHAR(50) UNIQUE,
    car_name VARCHAR(100) NOT NULL,
    customer_name VARCHAR(100) NOT NULL,
    customer_phone VARCHAR(30) NOT NULL,
    customer_email VARCHAR(100),
    start_date DATE,
    duration_days INT DEFAULT 1,
    rental_type VARCHAR(50) DEFAULT 'Lepas Kunci',
    total_price INT DEFAULT 0,
    status VARCHAR(30) DEFAULT 'Menunggu Konfirmasi', -- 'Menunggu Konfirmasi', 'Dikonfirmasi', 'Selesai', 'Batal'
    created_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE public.bookings ENABLE ROW LEVEL SECURITY;

-- Izinkan form dari website untuk memasukkan booking baru
CREATE POLICY "Akses publik untuk membuat booking" 
ON public.bookings 
FOR INSERT 
WITH CHECK (true);

